"""Resolve review/negatives.yaml plain-word signs to HPO terms through Q0 (spec §14).

Output `data/derived/negatives.resolved.yaml` is for the human to glance at; tuning reads it.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Literal, Protocol

import yaml
from pydantic import BaseModel, Field

ROOT = Path(__file__).resolve().parents[3]
NEGATIVES_PATH = ROOT / "review" / "negatives.yaml"
RESOLVED_PATH = ROOT / "data" / "derived" / "negatives.resolved.yaml"
CURATED_PATH = ROOT / "data" / "derived" / "negatives.curated.yaml"
Expected = Literal["no_escalation", "see_doctor_ok"]


class Resolver(Protocol):
    def resolve(self, text: str, k: int = 3) -> list[Any]: ...


class NegativeCase(BaseModel):
    id: str
    age_months: int
    summary: str
    present: list[str]
    absent: list[str] = Field(default_factory=list)
    expected: Expected


class ResolvedSign(BaseModel):
    phrase: str
    term: str | None
    name: str | None
    alternatives: list[str] = Field(default_factory=list)
    via: Literal["curated", "auto", "dropped"] = "auto"


class ResolvedNegative(BaseModel):
    id: str
    age_months: int
    summary: str
    expected: Expected
    present: list[ResolvedSign]
    absent: list[ResolvedSign]


def load_negatives(path: Path = NEGATIVES_PATH) -> list[NegativeCase]:
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    return [NegativeCase.model_validate(c) for c in raw["cases"]]


def load_curated(path: Path = CURATED_PATH) -> dict[str, dict[str, str | None]]:
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    return {k: dict(raw.get(k) or {}) for k in ("present", "absent")}


def _resolve_phrase(
    resolver: Resolver,
    phrase: str,
    curated: dict[str, str | None],
    names: dict[str, str],
) -> ResolvedSign:
    if phrase in curated:
        term = curated[phrase]
        if term is None:
            return ResolvedSign(phrase=phrase, term=None, name=None, via="dropped")
        return ResolvedSign(phrase=phrase, term=term, name=names.get(term), via="curated")
    hits = resolver.resolve(phrase, k=3)
    if not hits:
        return ResolvedSign(phrase=phrase, term=None, name=None)
    return ResolvedSign(
        phrase=phrase,
        term=hits[0].id,
        name=hits[0].name,
        alternatives=[f"{h.id} {h.name}" for h in hits[1:]],
    )


def resolve_negatives(
    cases: list[NegativeCase],
    resolver: Resolver,
    curated: dict[str, dict[str, str | None]] | None = None,
    names: dict[str, str] | None = None,
) -> list[ResolvedNegative]:
    cur = curated or {"present": {}, "absent": {}}
    nm = names or {}
    return [
        ResolvedNegative(
            id=c.id,
            age_months=c.age_months,
            summary=c.summary,
            expected=c.expected,
            present=[_resolve_phrase(resolver, p, cur["present"], nm) for p in c.present],
            absent=[_resolve_phrase(resolver, p, cur["absent"], nm) for p in c.absent],
        )
        for c in cases
    ]


def load_resolved(path: Path = RESOLVED_PATH) -> list[ResolvedNegative]:
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    return [ResolvedNegative.model_validate(c) for c in raw["cases"]]


def main() -> None:
    from app.graph.client import connect, rows
    from app.kb.info import load_kb_info
    from app.kb.resolve import TermResolver
    from app.llm.adapters.embedding import get_embedder

    info = load_kb_info()
    if info is None:
        raise SystemExit("no kb built; run `make kb` first")
    graph = connect().select_graph(info.release)
    embedder = get_embedder("bge", ROOT / "data" / "derived" / "embeddings.bge.bin")
    curated = load_curated()
    ids = sorted({t for sect in curated.values() for t in sect.values() if t})
    names = {str(r["id"]): str(r["name"]) for r in rows(graph, "q2h_term_names", {"ids": ids})}
    missing = [t for t in ids if t not in names]
    if missing:
        raise SystemExit(f"curated terms missing from kb: {missing}")
    out = resolve_negatives(load_negatives(), TermResolver(graph, embedder), curated, names)
    header = (
        "# Generated by `python -m app.eval.negatives` from review/negatives.yaml. Do not edit.\n"
    )
    body = yaml.safe_dump({"cases": [c.model_dump() for c in out]}, sort_keys=False, width=100)
    RESOLVED_PATH.write_text(header + body, encoding="utf-8")
    unresolved = sum(s.term is None and s.via == "auto" for c in out for s in c.present + c.absent)
    print(f"resolved {len(out)} cases; unresolved phrases: {unresolved}")  # noqa: T201


if __name__ == "__main__":
    main()
