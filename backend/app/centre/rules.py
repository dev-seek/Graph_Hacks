AGE_BANDS = ((36, "0-2y"), (72, "3-5y"), (144, "6-11y"), (216, "12-17y"), (10_000, "18-20y"))


def age_band(age_months: float | None) -> str:
    if age_months is None:
        return "unknown"
    for limit, label in AGE_BANDS:
        if age_months < limit:
            return label
    return "18-20y"


