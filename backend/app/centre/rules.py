def pick_clinician(systems: Iterable[str | None]) -> str:
    """Clinician for the most frequent body system among a case's signs (ties: smallest id).

    Uses signs only, never the diagnosis, so open and resolved cases are routed the same way.
    """
    votes = Counter(SYSTEM_TO_CLINICIAN[s] for s in systems if s in SYSTEM_TO_CLINICIAN)
    if not votes:
        return DEFAULT_CLINICIAN
    top = max(votes.values())
    return min(c for c, n in votes.items() if n == top)


