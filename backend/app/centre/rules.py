def pick_protocol(diagnosis_name: str, clinician_id: str) -> ProtocolSpec:
    """Protocol by diagnosis keywords; else panel for panel-friendly specialties, else exome."""
    name = diagnosis_name.lower() + " "
    for pid, words in _KEYWORDS:
        if any(w in name for w in words):
            return _BY_ID[pid]
    return _BY_ID["PR-3" if clinician_id in _PANEL_FRIENDLY else "PR-4"]


def turnaround_days(protocol: ProtocolSpec, rng: random.Random) -> int:
    """Base days for the protocol, +/-30% seeded jitter."""
    return max(3, round(protocol.base_days * rng.uniform(0.7, 1.3)))
